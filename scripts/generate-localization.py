#!/usr/bin/env python3
"""Validate canonical message catalogs and generate offline platform dictionaries."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    en = json.loads((ROOT / 'localization/en.json').read_text())
    catalogs = {language: json.loads((ROOT / f'localization/{language}.json').read_text())
                for language in ('zh-Hans', 'it')}
    for language, catalog in catalogs.items():
        if en.keys() != catalog.keys():
            raise ValueError(f'Catalog keys differ: {language}')
        for key, value in en.items():
            if key != value or not isinstance(catalog[key], str) or not catalog[key].strip():
                raise ValueError(f'Invalid message ({language}): {key}')
            if sorted(re.findall(r'\{\d+\}', key)) != sorted(re.findall(r'\{\d+\}', catalog[key])):
                raise ValueError(f'Placeholder mismatch ({language}): {key}')
    legacy = json.loads((ROOT/'localization/legacy-messages.json').read_text())
    if any(key not in en for key in legacy.values()): raise ValueError('Unknown legacy message target')
    banner = '// Generated by scripts/generate-localization.py. Edit localization/*.json.\n'
    result = {'host/nodelift/i18n.js': banner + 'const NodeLiftLegacy = '+json.dumps(legacy,ensure_ascii=False)
              + ';\nconst NodeLiftChinese = '+json.dumps(catalogs['zh-Hans'],ensure_ascii=False,indent=2)
              + ';\nconst NodeLiftItalian = '+json.dumps(catalogs['it'],ensure_ascii=False,indent=2)
              + ';\nconst NodeLiftCatalogs = {\"zh-Hans\": NodeLiftChinese, it: NodeLiftItalian};\n'
              + (ROOT/'localization/dashboard-runtime.js').read_text()}
    for language, name in (('zh-Hans', 'Chinese'), ('it', 'Italian')):
        catalog = catalogs[language]
        data = json.dumps(catalog, ensure_ascii=False, indent=2)
        variable = name.lower()+'Messages'
        swift = ',\n'.join('    '+json.dumps(k,ensure_ascii=False)+': '+json.dumps(v,ensure_ascii=False) for k,v in catalog.items())
        result[f'apps/android/app/src/main/assets/{language}.json'] = data+'\n'
        result[f'apps/ios/NodeLift/{name}Messages.swift'] = banner+f'let {variable}: [String: String] = [\n'+swift+'\n]\n'
        result[f'apps/harmony/entry/src/main/ets/pages/{name}Messages.ets'] = banner+f'export const {variable}: Record<string, string> = '+data+';\n'
    return result


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    stale=[]
    for name, content in outputs().items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=content:stale.append(name)
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content)
    if stale:raise SystemExit('Stale generated files: '+', '.join(stale))
    print('Localization catalogs and generated assets verified.' if args.check else 'Localization assets generated.')


if __name__=='__main__':main()
