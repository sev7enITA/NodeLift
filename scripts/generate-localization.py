#!/usr/bin/env python3
"""Validate canonical message catalogs and generate offline platform dictionaries."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def outputs():
    en = json.loads((ROOT / 'localization/en.json').read_text())
    zh = json.loads((ROOT / 'localization/zh-Hans.json').read_text())
    if en.keys() != zh.keys():
        raise ValueError('Catalog keys differ')
    for key, value in en.items():
        if key != value or not zh[key].strip():
            raise ValueError(f'Invalid message: {key}')
        if sorted(re.findall(r'\{\d+\}', key)) != sorted(re.findall(r'\{\d+\}', zh[key])):
            raise ValueError(f'Placeholder mismatch: {key}')
    data = json.dumps(zh, ensure_ascii=False, indent=2)
    legacy = json.loads((ROOT/'localization/legacy-messages.json').read_text())
    if any(key not in en for key in legacy.values()): raise ValueError('Unknown legacy message target')
    banner = '// Generated by scripts/generate-localization.py. Edit localization/*.json.\n'
    swift = ',\n'.join('    '+json.dumps(k,ensure_ascii=False)+': '+json.dumps(v,ensure_ascii=False) for k,v in zh.items())
    return {
        'host/nodelift/i18n.js': banner + 'const NodeLiftLegacy = '+json.dumps(legacy,ensure_ascii=False)+';\nconst NodeLiftChinese = '+data+';\n' + (ROOT/'localization/dashboard-runtime.js').read_text(),
        'apps/android/app/src/main/assets/zh-Hans.json': data+'\n',
        'apps/ios/NodeLift/ChineseMessages.swift': banner+'let chineseMessages: [String: String] = [\n'+swift+'\n]\n',
        'apps/harmony/entry/src/main/ets/pages/ChineseMessages.ets': banner+'export const chineseMessages: Record<string, string> = '+data+';\n',
    }


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    stale=[]
    for name, content in outputs().items():
        path=ROOT/name
        if args.check:
            if not path.exists() or path.read_text()!=content:stale.append(name)
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content)
    if stale:raise SystemExit('Stale generated files: '+', '.join(stale))
    print('Localization catalogs and generated assets verified.' if args.check else 'Localization assets generated.')


if __name__=='__main__':main()
