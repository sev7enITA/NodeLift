#!/usr/bin/env python3
"""Generate English release history and reject undocumented or inconsistent builds."""
import argparse
from datetime import datetime
from html import escape
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
START, END = '<!-- RELEASE_HISTORY:START -->', '<!-- RELEASE_HISTORY:END -->'
RELEASE_BASE = 'https://github.com/sev7enITA/NodeLift/releases/tag/v'


def validate(data, root=ROOT, build_only=False):
    errors = []
    if data.get('schema_version') != 1 or data.get('documentation_language') != 'en':
        errors.append('History requires schema_version 1 and English documentation')
    releases = data.get('releases', [])
    if not isinstance(releases, list) or not releases:
        return errors + ['Release history must contain at least one release']
    versions, builds, previous = set(), set(), None
    for item in releases:
        version, build = item.get('version', ''), item.get('build')
        valid_version = isinstance(version, str) and re.fullmatch(r'\d+\.\d+\.\d+', version)
        valid_build = type(build) is int and build > 0
        if not valid_version or not valid_build:
            errors.append('Every release needs a semantic version and positive integer build')
            continue
        if version in versions or build in builds:
            errors.append(f'Duplicate release version/build: {version}/{build}')
        versions.add(version); builds.add(build)
        if previous is not None and (tuple(map(int, version.split('.'))) >= previous[0] or build >= previous[1]):
            errors.append('Release versions and builds must be strictly newest first')
        previous = (tuple(map(int, version.split('.'))), build)
        if item.get('url') != RELEASE_BASE + version:
            errors.append(f'{version}: release URL must identify its exact GitHub tag')
        try:
            if not (build_only and item.get('published_at') is None):
                datetime.strptime(item.get('published_at', ''), '%Y-%m-%dT%H:%M:%SZ')
        except (ValueError, TypeError):
            errors.append(f'{version}: published_at must be a UTC publication timestamp')
        for key in ('title', 'validation', 'limitations', 'status'):
            if not isinstance(item.get(key), str) or not item[key].strip():
                errors.append(f'{version}: missing {key}')
        if not isinstance(item.get('changes'), list) or not item['changes'] or any(not isinstance(c, str) or not c.strip() for c in item['changes']):
            errors.append(f'{version}: changes must be a nonempty list of text')
    latest = releases[0]
    android = (root/'apps/android/app/build.gradle.kts').read_text()
    ios = (root/'apps/ios/project.yml').read_text()
    def field(text, pattern):
        match = re.search(pattern, text)
        return match.group(1) if match else None
    expected = (str(latest.get('version')), str(latest.get('build')))
    for platform, identity in (
        ('Android', (field(android, r'versionName\s*=\s*"([^"]+)"'), field(android, r'versionCode\s*=\s*(\d+)'))),
        ('iOS', (field(ios, r'MARKETING_VERSION:\s*(\S+)'), field(ios, r'CURRENT_PROJECT_VERSION:\s*(\d+)'))),
    ):
        if identity != expected:
            errors.append(f'{platform} version/build {identity} lacks matching latest history entry {expected}')
    if not build_only:
        portal = json.loads((root/'site/NodeLift/data/mobile-downloads.json').read_text())
        if (str(portal.get('version')), str(portal.get('build'))) != expected:
            errors.append('Portal download metadata differs from latest documented build')
    for update in data.get('documentation_updates', []):
        if not update.get('date') or not update.get('title') or not update.get('changes'):
            errors.append('Documentation updates require date, title and changes')
    return errors


def render_markdown(data):
    lines = ['# Changelog', '', '<!-- Generated by scripts/release-history.py from releases/history.json. -->', '',
             'Every published companion build has an entry below. Android packages are laboratory builds; iOS packages require Apple signing and provisioning. Historical validation belongs to the named version and does not establish current physical-device performance.', '']
    for item in data['releases']:
        lines += [f"## [{item['version']}]({item['url']}): build {item['build']} · {item['published_at'][:10]}", '',
                  f"**{item['title']}** · {item['status']}", '']
        lines += ['- '+change for change in item['changes']]
        lines += ['', '**Validation:** '+item['validation'], '', '**Limits:** '+item['limitations'], '']
    if data.get('documentation_updates'):
        lines += ['## Host, documentation and tooling updates', '']
        for update in data['documentation_updates']:
            lines += [f"### {update['date']}: {update['title']}", '']
            lines += ['- '+change for change in update['changes']]
            lines += ['']
    lines += ['Publication dates are UTC. Companion versions and the host preview version are separate. Original published binaries and tags are not rewritten for documentation corrections.', '']
    return '\n'.join(lines)


def render_html(data):
    lines = ['<div class="release-history" lang="en">']
    for i, item in enumerate(data['releases']):
        opening = ' open' if i == 0 else ''
        lines += [f'<details class="release-entry"{opening}>',
                  f'<summary><strong>{escape(item["version"])} · build {item["build"]}</strong>: {escape(item["title"])}<span class="release-meta"><time datetime="{item["published_at"]}">{item["published_at"][:10]} UTC</time> · {escape(item["status"])}</span></summary>',
                  '<div class="release-body"><ul>']
        lines += ['<li>'+escape(change)+'</li>' for change in item['changes']]
        lines += ['</ul><p><strong>Validation:</strong> '+escape(item['validation'])+'</p>',
                  '<p><strong>Limits:</strong> '+escape(item['limitations'])+'</p>',
                  f'<p><a href="{escape(item["url"], quote=True)}" target="_blank" rel="noopener noreferrer">Release assets and original notes ↗</a></p></div></details>']
    if data.get('documentation_updates'):
        lines += ['<details class="release-entry"><summary><strong>Host, documentation and tooling updates</strong></summary><div class="release-body">']
        for update in data['documentation_updates']:
            lines += ['<h3>'+escape(update['date']+': '+update['title'])+'</h3><ul>']
            lines += ['<li>'+escape(change)+'</li>' for change in update['changes']]
            lines += ['</ul>']
        lines += ['</div></details>']
    lines += ['</div>']
    return '\n'.join(lines)


def outputs(data, root=ROOT):
    page = (root/'site/NodeLift/index.html').read_text()
    if page.count(START) != 1 or page.count(END) != 1 or page.index(START) >= page.index(END):
        raise ValueError('Portal needs one ordered RELEASE_HISTORY marker pair')
    head, rest = page.split(START)
    _, tail = rest.split(END)
    markdown = render_markdown(data)
    return {
        root/'CHANGELOG.md': markdown,
        root/'site/NodeLift/data/changelog.md': markdown,
        root/'site/NodeLift/data/changelog.json': json.dumps(data, indent=2, ensure_ascii=False)+'\n',
        root/'site/NodeLift/index.html': head+START+'\n'+render_html(data)+'\n'+END+tail,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true', help='Check versions, portal metadata and all generated files')
    mode.add_argument('--check-build', action='store_true', help='Require Android/iOS version and build notes before compiling; portal publication may follow')
    args = parser.parse_args()
    data = json.loads((ROOT/'releases/history.json').read_text())
    errors = validate(data, build_only=args.check_build)
    changed = []
    if not errors and not args.check_build:
        for path, content in outputs(data).items():
            if not path.exists() or path.read_text() != content:
                changed.append(str(path.relative_to(ROOT)))
                if not args.check:
                    path.write_text(content)
        if args.check:
            errors.extend('Stale generated release history: '+path for path in changed)
    print(json.dumps({'latest': data['releases'][0]['version'], 'build': data['releases'][0]['build'], 'generated_files_changed': changed, 'errors': errors}, indent=2))
    raise SystemExit(bool(errors))


if __name__ == '__main__':
    main()
