from typing import *
import functools,time
import mlx.core as mx
import mlx.nn as nn
from mlx_lm.generate import generation_stream,DEFAULT_QUANTIZED_KV_START,maybe_quantize_kv_cache
from mlx_lm.models.cache import make_prompt_cache,can_trim_prompt_cache,trim_prompt_cache
from mlx_lm.sample_utils import Sampler,LogitsProcessor,greedy_sampler

def accounted_generate_step(
    prompt: mx.array,
    model: nn.Module,
    draft_model: nn.Module,
    stream: mx.Stream | mx.ThreadLocalStream = generation_stream,
    *,
    num_draft_tokens: int = 2,
    policy=None,
    trace=None,
    telemetry=None,
    max_tokens: int = 256,
    sampler: Optional[Sampler] = None,
    logits_processors: Optional[List[LogitsProcessor]] = None,
    prompt_cache: Optional[Any] = None,
    prefill_step_size: int = 512,
    kv_bits: Optional[int] = None,
    kv_group_size: int = 64,
    quantized_kv_start: int = DEFAULT_QUANTIZED_KV_START,
) -> Generator[Tuple[mx.array, mx.array, bool], None, None]:
    """
    A generator producing token ids based on the given prompt from the model.

    Args:
        prompt (mx.array): The input prompt.
        model (nn.Module): The model to use for generation.
        draft_model (nn.Module): The draft model for speculative decoding.
        num_draft_tokens (int, optional): The number of draft tokens for
          speculative decoding. Default: ``2``.
        max_tokens (int): The maximum number of tokens. Use``-1`` for an infinite
          generator. Default: ``256``.
        sampler (Sampler, optional): A sampler for sampling a
          token from a vector of log probabilities. Default: ``None``.
        logits_processors (List[LogitsProcessor], optional):
          A list of functions that take tokens and logits and return the processed
          logits. Default: ``None``.
        prompt_cache (List[Any], optional): A pre-computed prompt cache. Note, if
          provided, the cache will be updated in place. The cache must be trimmable.
        prefill_step_size (int): Step size for processing the prompt.
        kv_bits (int, optional): Number of bits to use for KV cache quantization.
          None implies no cache quantization. Default: ``None``.
        kv_group_size (int): Group size for KV cache quantization. Default: ``64``.
        quantized_kv_start (int): Step to begin using a quantized KV cache.
           when ``kv_bits`` is non-None. Default: ``5000``.

    Yields:
        Tuple[mx.array, mx.array, bool]: One token, a vector of log probabilities,
          and a bool indicating if the token was generated by the draft model
    """

    telemetry = telemetry if telemetry is not None else {}
    y = prompt.astype(mx.uint32)
    prev_tokens = None

    # Create the KV cache for generation
    if prompt_cache is None:
        model_cache = make_prompt_cache(model)
        draft_cache = make_prompt_cache(draft_model)
    else:
        model_cache = prompt_cache[: len(model.layers)]
        draft_cache = prompt_cache[len(model.layers) :]

    if not can_trim_prompt_cache(model_cache):
        types = {type(c).__name__ for c in model_cache if not c.is_trimmable()}
        raise ValueError(
            f"Speculative decoding requires a trimmable prompt cache " f"(got {types})."
        )

    sampler = sampler or greedy_sampler

    quantize_cache_fn = functools.partial(
        maybe_quantize_kv_cache,
        quantized_kv_start=quantized_kv_start,
        kv_group_size=kv_group_size,
        kv_bits=kv_bits,
    )

    def _process_and_sample(tokens, logits):
        if logits_processors:
            for processor in logits_processors:
                logits = processor(tokens, logits)

        logprobs = logits - mx.logsumexp(logits, axis=-1, keepdims=True)
        y = sampler(logprobs)
        return y, logprobs

    def _step(model, cache, y, n_predict=1):
        logits = model(y[None], cache=cache)
        logits = logits[:, -n_predict:, :]

        quantize_cache_fn(cache)
        if logits_processors:
            nonlocal prev_tokens
            out_y, out_logprobs = [], []
            if n_predict > 1:
                y = y[: -(n_predict - 1)]
            for i in range(n_predict):
                prev_tokens = (
                    mx.concatenate([prev_tokens, y]) if prev_tokens is not None else y
                )
                y, logprobs = _process_and_sample(prev_tokens, logits[:, i, :])
                out_y.append(y)
                out_logprobs.append(logprobs)
            return mx.concatenate(out_y, axis=0), mx.concatenate(out_logprobs, axis=0)
        else:
            return _process_and_sample(None, logits.squeeze(0))

    def _prefill(model, cache, y):
        while y.size > 1:
            n_to_process = min(prefill_step_size, y.size - 1)
            model(y[:n_to_process][None], cache=cache)
            quantize_cache_fn(cache)
            mx.eval([c.state for c in cache])
            y = y[n_to_process:]
            mx.clear_cache()
        return y

    def _rewind_cache(num_draft, num_accept):
        trim_prompt_cache(model_cache, num_draft - num_accept)
        trim_prompt_cache(draft_cache, max(num_draft - num_accept - 1, 0))

    def _draft_generate(y, num_draft):
        if num_draft == 0:
            return mx.array([], mx.uint32)
        ys = []
        for _ in range(num_draft):
            y, _ = _step(draft_model, draft_cache, y)
            mx.async_eval(y)
            ys.append(y)
        return mx.concatenate(ys)

    with mx.stream(stream):
        prefill_start = time.perf_counter()
        draft_y = _prefill(draft_model, draft_cache, y)
        mx.eval([c.state for c in draft_cache])
        draft_prefilled = time.perf_counter()
        y = _prefill(model, model_cache, y)
        mx.eval([c.state for c in model_cache])
        telemetry['draft_prefill_seconds'] = draft_prefilled-prefill_start
        telemetry['target_prefill_seconds'] = time.perf_counter()-draft_prefilled
        first_block = True

        ntoks = 0
        # Set these so the finally block doesn't raise
        num_draft = 0
        n = 0
        try:
            while True:
                num_draft = min(max_tokens - ntoks, policy.choose() if policy else num_draft_tokens)
                block_started = time.perf_counter()
                draft_tokens = _draft_generate(draft_y, num_draft)
                mx.eval(draft_tokens)
                drafted_at = time.perf_counter()
                if prev_tokens is not None:
                    prev_tokens = prev_tokens[
                        : prev_tokens.size - y.size - num_draft + 1
                    ]
                y = mx.concatenate([y, draft_tokens])
                tokens, logprobs = _step(model, model_cache, y, num_draft + 1)
                mx.eval(tokens, draft_tokens)
                draft_tokens = draft_tokens.tolist()
                tokens = tokens.tolist()
                verified_at = time.perf_counter()
                row = {"k": num_draft, "accepted": 0, "emitted": 0, "draft_seconds": drafted_at-block_started, "verify_seconds": verified_at-drafted_at}
                if trace is not None: trace.append(row)
                n = 0
                while n < num_draft:
                    tn, dtn, lpn = tokens[n], draft_tokens[n], logprobs[n]
                    if tn != dtn:
                        break
                    n += 1
                    ntoks += 1
                    row["accepted"] += 1
                    row["emitted"] += 1
                    yield tn, lpn, True
                    if ntoks == max_tokens:
                        break
                if ntoks < max_tokens:
                    ntoks += 1
                    row["emitted"] += 1
                    yield tokens[n], logprobs[n], False


                if ntoks == max_tokens:
                    break

                y = mx.array([tokens[n]], mx.uint32)
                draft_y = y

                # If we accepted all the draft tokens, include the last
                # draft token in the next draft step since it hasn't been
                # processed yet by the draft model
                if n == num_draft:
                    draft_y = mx.concatenate(
                        [mx.array(draft_tokens[-1:], mx.uint32), draft_y]
                    )

                if prev_tokens is not None:
                    prev_tokens = prev_tokens[: -max(num_draft - n, 1)]
                rewind_started = time.perf_counter()
                _rewind_cache(num_draft, n)
                row['rewind_seconds'] = time.perf_counter()-rewind_started
                row['wall_seconds'] = time.perf_counter()-block_started
                row['controller_charge_seconds'] = row['wall_seconds'] + (telemetry['draft_prefill_seconds'] if first_block else 0)
                first_block = False
                if policy: policy.observe(row)
        finally:
            cleanup_started = time.perf_counter()
            _rewind_cache(num_draft, n)
            telemetry['final_rewind_seconds'] = time.perf_counter()-cleanup_started
            if trace and 'wall_seconds' not in trace[-1]:
                trace[-1]['wall_seconds'] = time.perf_counter()-block_started
                trace[-1]['closed_before_policy_update'] = True
